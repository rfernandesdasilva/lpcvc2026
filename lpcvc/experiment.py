"""Numbered, self-describing experiment folders.

Every script runs inside an Experiment, which creates experiments/NNN_<slug>/ containing:
  README.md      question, how to reproduce, results, conclusions. The auto block is regenerated each run;
                 the text you write outside it is preserved.
  manifest.json  exact command, git commit (+ dirty flag), start/end time, status, versions, GPU, args
  log.txt        full console output of the run
  *.json / *.npz results written by the script
and refreshes experiments/INDEX.md (one row per experiment, in order).

Re-running with the same slug reuses the folder (after an `--exp-resume` or a failed run); a new slug gets
the next number.
"""
from __future__ import annotations

import io
import json
import platform
import re
import shlex
import subprocess
import sys
import traceback
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
EXP_DIR = ROOT / "experiments"
AUTO_BEGIN, AUTO_END = "<!-- AUTO:BEGIN (regenerated by lpcvc/experiment.py, edit outside this block) -->", "<!-- AUTO:END -->"


def _git(*args) -> str:
    try:
        return subprocess.check_output(["git", *args], cwd=ROOT, text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return ""


def _versions() -> dict:
    out = {"python": sys.version.split()[0], "platform": platform.platform()}
    for mod in ("torch", "open_clip", "timm", "transformers", "onnx", "onnxruntime", "qai_hub", "numpy"):
        try:
            out[mod] = __import__(mod).__version__
        except Exception:
            pass
    try:
        import torch
        out["gpu"] = torch.cuda.get_device_name(0) if torch.cuda.is_available() else None
    except Exception:
        pass
    return out


class _Tee(io.TextIOBase):
    def __init__(self, *streams):
        self.streams = streams

    def write(self, s):
        for st in self.streams:
            st.write(s)
            st.flush()
        return len(s)

    def flush(self):
        for st in self.streams:
            st.flush()


def _next_dir(slug: str) -> Path:
    EXP_DIR.mkdir(exist_ok=True)
    existing = sorted(p for p in EXP_DIR.iterdir() if p.is_dir() and re.match(r"^\d{3}_", p.name))
    for p in existing:
        if p.name[4:] == slug:
            return p
    n = int(existing[-1].name[:3]) + 1 if existing else 1
    return EXP_DIR / f"{n:03d}_{slug}"


class Experiment:
    def __init__(self, slug: str, title: str, question: str, args=None):
        if not re.fullmatch(r"[a-z0-9][a-z0-9\-]*", slug):
            raise ValueError("slug must be lowercase letters, digits and dashes")
        self.dir = _next_dir(slug)
        self.id = self.dir.name[:3]
        self.title, self.question = title, question
        self.args = vars(args) if args is not None and not isinstance(args, dict) else (args or {})
        self.headline = ""
        self.tables: list[str] = []

    # ---- outputs -------------------------------------------------------------------------------
    def path(self, name: str) -> Path:
        p = self.dir / name
        p.parent.mkdir(parents=True, exist_ok=True)
        return p

    def save_json(self, name: str, obj) -> Path:
        p = self.path(name)
        p.write_text(json.dumps(obj, indent=2, default=_jsonable), encoding="utf-8")
        return p

    def save_npz(self, name: str, **arrays) -> Path:
        p = self.path(name)
        np.savez(p, **arrays)
        return p

    def add_table(self, md: str) -> None:
        """Markdown table/text that goes into the README auto block."""
        self.tables.append(md)

    # ---- lifecycle -----------------------------------------------------------------------------
    def __enter__(self):
        self.dir.mkdir(parents=True, exist_ok=True)
        self.manifest = {
            "id": self.id, "slug": self.dir.name[4:], "title": self.title, "question": self.question,
            "command": shlex.join([".venv/python", Path(sys.argv[0]).resolve().relative_to(ROOT).as_posix(), *sys.argv[1:]]),
            "git_commit": _git("rev-parse", "HEAD"), "git_dirty": bool(_git("status", "--porcelain", "--", "lpcvc", "scripts")),
            "started_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "args": self.args, "env": _versions(), "status": "running",
        }
        self.save_json("manifest.json", self.manifest)
        self._log = open(self.dir / "log.txt", "a", encoding="utf-8")
        self._log.write(f"\n===== {self.manifest['started_utc']}  {self.manifest['command']}\n")
        self._stdout = sys.stdout
        sys.stdout = _Tee(self._stdout, self._log)
        print(f"[experiment {self.dir.name}] {self.title}")
        return self

    def __exit__(self, exc_type, exc, tb):
        sys.stdout = self._stdout
        if exc_type is not None:
            self._log.write("".join(traceback.format_exception(exc_type, exc, tb)))
        self._log.close()
        self.manifest.update({
            "finished_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "status": "ok" if exc_type is None else f"failed: {exc_type.__name__}: {exc}",
            "headline": self.headline,
        })
        self.save_json("manifest.json", self.manifest)
        self._write_readme()
        write_index()
        return False

    def _write_readme(self):
        m = self.manifest
        auto = "\n".join([
            AUTO_BEGIN,
            f"**Status:** {m['status']}  ",
            f"**Run:** {m['started_utc']} → {m.get('finished_utc', '')} (UTC)  ",
            f"**Code:** commit `{m['git_commit'][:10]}`{' (+ uncommitted changes in lpcvc/ or scripts/)' if m['git_dirty'] else ''}  ",
            f"**Hardware/software:** {m['env'].get('gpu')}, {m['env'].get('platform')}, torch {m['env'].get('torch')}, "
            f"open_clip {m['env'].get('open_clip')}, qai_hub {m['env'].get('qai_hub')}",
            "",
            "**Reproduce:**",
            "```bash",
            m["command"],
            "```",
            "",
            *(f"{t}\n" for t in self.tables),
            f"**Headline:** {self.headline}" if self.headline else "",
            "",
            "Files: `manifest.json` (exact environment and args), `log.txt` (full console output), result JSON/NPZ files.",
            AUTO_END,
        ])
        readme = self.dir / "README.md"
        if readme.exists() and AUTO_BEGIN in readme.read_text(encoding="utf-8"):
            txt = readme.read_text(encoding="utf-8")
            txt = txt[:txt.index(AUTO_BEGIN)] + auto + txt[txt.index(AUTO_END) + len(AUTO_END):]
        else:
            txt = (f"# {self.id} · {self.title}\n\n## Question\n{self.question}\n\n## Setup and results\n{auto}\n\n"
                   f"## Conclusions\n_TODO: what we learned, what we decided, what comes next._\n")
        readme.write_text(txt, encoding="utf-8")


def write_index():
    rows = []
    for p in sorted(EXP_DIR.glob("[0-9][0-9][0-9]_*/manifest.json")):
        m = json.loads(p.read_text(encoding="utf-8"))
        rows.append(f"| [{m['id']}]({p.parent.name}/README.md) | {m['started_utc'][:10]} | {m['title']} | "
                    f"{m['status'].split(':')[0]} | {m.get('headline', '')} | `{m['git_commit'][:7]}` |")
    (EXP_DIR / "INDEX.md").write_text(
        "# Experiment index\n\nIn the order they were run. Each folder has a README (question, how to reproduce, "
        "results, conclusions), `manifest.json` (exact command, commit, versions) and `log.txt`.\n\n"
        "| ID | Date | Experiment | Status | Headline | Commit |\n|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n",
        encoding="utf-8")


def _jsonable(o):
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, Path):
        return str(o)
    return str(o)
